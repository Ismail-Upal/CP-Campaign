void Solve(){
    int n, m; cin >> n >> m;
    int d = m / n;
    int r = m % n;
    for(int i = 1; i <= n; i++){
        if(r){
            cout << d + 1 << endl;
            r--;
        }
        else cout << d << endl;
    }
}

